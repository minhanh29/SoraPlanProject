#!/usr/bin/env bash
# Build and deploy SoraPlan.
#
#   deploy/deploy.sh worker     # plan parsing worker -> Cloud Run (private)
#   deploy/deploy.sh api        # API -> Cloud Run (public, auth in app)
#   deploy/deploy.sh frontend   # static frontend -> Firebase Hosting
#   deploy/deploy.sh all        # worker, api, frontend in that order
#
# Run deploy/setup.sh once before the first deploy.

source "$(dirname "${BASH_SOURCE[0]}")/config.sh"

ENV_YAML="$(mktemp)"
trap 'rm -f "$ENV_YAML"' EXIT

deploy_worker() {
  local model
  model="$(env_get "$WORKER_ENV_FILE" OPENAI_MODEL)"

  log "Deploying $WORKER_SERVICE from backend/plan_parsing_worker"
  cat > "$ENV_YAML" <<EOF
ENV: production
FIREBASE_PROJECT_ID: "$PROJECT_ID"
GCS_BUCKET_NAME: "$UPLOADS_BUCKET"
OPENAI_MODEL: "${model:-gpt-6-sol}"
EOF

  gc run deploy "$WORKER_SERVICE" \
    --source="$REPO_ROOT/backend/plan_parsing_worker" \
    --region="$REGION" \
    --service-account="$WORKER_SA" \
    --no-allow-unauthenticated \
    --env-vars-file="$ENV_YAML" \
    --set-secrets="OPENAI_API_KEY=${SECRET_OPENAI_API_KEY}:latest" \
    --memory=1Gi --cpu=1 \
    --timeout=600 \
    --concurrency=4 \
    --min-instances=0 --max-instances=3

  # Only the API (direct fallback) and Cloud Tasks (OIDC) may invoke the worker
  for sa in "$API_SA" "$TASKS_SA"; do
    gc run services add-iam-policy-binding "$WORKER_SERVICE" --region="$REGION" \
      --member="serviceAccount:$sa" --role=roles/run.invoker >/dev/null
  done
  log "Worker: $(service_url "$WORKER_SERVICE") (private)"
}

deploy_api() {
  local worker_url
  worker_url="$(service_url "$WORKER_SERVICE")"
  [ -n "$worker_url" ] || die "Worker not deployed yet. Run: deploy/deploy.sh worker"

  log "Deploying $API_SERVICE from backend/api"
  cat > "$ENV_YAML" <<EOF
ENV: production
FIREBASE_PROJECT_ID: "$PROJECT_ID"
GCS_BUCKET_NAME: "$UPLOADS_BUCKET"
CATALOG_BUCKET_NAME: "$CATALOG_BUCKET"
PLAN_PARSER_WORKER_URL: "$worker_url"
CLOUD_TASKS_QUEUE: "$TASKS_QUEUE_PATH"
TASKS_INVOKER_SA: "$TASKS_SA"
WORKER_REQUIRES_AUTH: "true"
CORS_ORIGINS: "${HOSTING_ORIGINS},${LOCAL_ORIGINS}"
ADMIN_UIDS: "$(env_get "$API_ENV_FILE" ADMIN_UIDS)"
EOF

  gc run deploy "$API_SERVICE" \
    --source="$REPO_ROOT/backend/api" \
    --region="$REGION" \
    --service-account="$API_SA" \
    --allow-unauthenticated \
    --env-vars-file="$ENV_YAML" \
    --set-secrets="FIREBASE_WEB_API_KEY=${SECRET_FIREBASE_WEB_API_KEY}:latest,MESHY_API_KEY=${SECRET_MESHY_API_KEY}:latest" \
    --memory=1Gi --cpu=1 \
    --timeout=300 \
    --min-instances=0 --max-instances=5

  log "API: $(service_url "$API_SERVICE")"
}

deploy_frontend() {
  local api_url build="$REPO_ROOT/build/frontend"
  api_url="$(service_url "$API_SERVICE")"
  [ -n "$api_url" ] || die "API not deployed yet. Run: deploy/deploy.sh api"
  command -v firebase >/dev/null || die "Firebase CLI not found: npm i -g firebase-tools"

  log "Staging frontend in build/frontend"
  rm -rf "$build" && mkdir -p "$build"
  rsync -a --exclude README.md --exclude package.json --exclude assets "$REPO_ROOT/frontend/" "$build/"
  cat > "$build/config.js" <<EOF
// Generated by deploy/deploy.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)
window.SORAPLAN_CONFIG = {
  API_BASE_URL: "${api_url}/v1",
  CATALOG_BASE_URL: "https://storage.googleapis.com/${CATALOG_BUCKET}",
};
EOF

  log "Deploying to Firebase Hosting ($PROJECT_ID)"
  (cd "$REPO_ROOT" && firebase deploy --only hosting --project "$PROJECT_ID" --non-interactive)
  log "Frontend: https://${PROJECT_ID}.web.app"
}

case "${1:-}" in
  worker) deploy_worker ;;
  api) deploy_api ;;
  frontend|fe) deploy_frontend ;;
  all) deploy_worker; deploy_api; deploy_frontend ;;
  *) echo "usage: $0 {worker|api|frontend|all}" >&2; exit 2 ;;
esac
